'use strict';
const assert = require('node:assert/strict');
require('../js/vendor/prism-qr-encoder.js');
require('../js/prism-employee-qr.js');
const { buildCard, svgFor } = globalThis.PrismEmployeeQr;
const sample={first:'Test',last:'Employee',title:'Travel Advisor',phone:'+91 98765 43210',email:'test@example.com',address:true,social1:'https://example.com/profile'};
const {card,filename}=buildCard(sample);
assert.equal(filename,'prism-test-employee');
assert.ok(card.startsWith('BEGIN:VCARD\r\nVERSION:3.0\r\n'));
assert.ok(card.includes('N:Employee;Test;;;\r\n'));
assert.ok(card.includes('TEL;TYPE=WORK,CELL:+919876543210\r\n'));
assert.ok(card.includes('URL:https://tripbyprism.co.in\r\n'));
assert.ok(card.includes('ADR;TYPE=WORK:;;HSIIDC IT Park\\, Sector-22;Panchkula;Haryana;134109;India'));
assert.ok(card.endsWith('END:VCARD\r\n'));
assert.ok(!buildCard({...sample,address:false}).card.includes('ADR;'));
assert.ok(buildCard({...sample,title:'Sales, Travel; Ops\\Team'}).card.includes('TITLE:Sales\\, Travel\\; Ops\\\\Team'));
const unicode=buildCard({...sample,first:'अनन्या',last:'शर्मा',title:'यात्रा सलाहकार'}).card;
assert.ok(unicode.includes('अनन्या'));
const folded=buildCard({...sample,social1:'https://example.com/'+ 'a'.repeat(90)}).card;
assert.ok(folded.includes('\r\n '));
for(const line of folded.split('\r\n')) assert.ok(Buffer.byteLength(line)<=75);
for(const extra of [{phone:'12345'},{email:'wrong'},{title:'x\r\nTEL:evil'},{social1:'javascript:alert(1)'},{social1:'https://a:b@example.com'}]) assert.throws(()=>buildCard({...sample,...extra}));
const matrix=globalThis.PrismQrEncoder(card);
assert.ok(matrix.length>=21 && matrix.every(row=>row.length===matrix.length && row.every(x=>typeof x==='boolean')));
assert.ok(svgFor(matrix).includes(`viewBox="0 0 ${matrix.length+8} ${matrix.length+8}"`));
console.log('Employee QR unit tests passed.');
